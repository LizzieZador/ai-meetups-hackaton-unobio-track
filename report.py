"""Render the final list of Claims into a Markdown report.

The report is generated BY FORMATTING these objects, not by asking an LLM to
"write a report" freely — that's what keeps the evidence/inference labels intact
and gives automatic traceability (see plan).
"""
import datetime

from schema import Claim

BADGE = {"evidence": "EVIDENCE", "inference": "INFERENCE"}


def render_report(indication: str, mechanism: str, claims: list[Claim]) -> str:
    lines = [
        f"# Investment Report: {mechanism} — {indication}",
        f"_Generated {datetime.date.today().isoformat()}_",
        "",
    ]
    for c in claims:
        badge = BADGE.get(c.type, c.type)
        lines.append(f"- **{c.claim}** `[{badge}]`")
        if c.type == "evidence":
            link = f"[{c.source}]({c.url})" if c.url else c.source
            lines.append(f"  - source: {link} (accessed {c.date_accessed})")
        else:
            lines.append(f"  - reasoning: {c.reasoning} (confidence: {c.confidence})")
    return "\n".join(lines)
