"""Render the final list of Claims into a Markdown Investment Underwriting Report.

The report is generated BY FORMATTING these objects into the exact section list
from the task brief's "Required Output", not by asking an LLM to "write a report"
freely — that keeps the evidence/inference labels intact and gives automatic
traceability. "Sources Supporting Major Claims" is assembled here from evidence
claims rather than generated by any agent — code, not the LLM, owns that structure.
"""
import datetime
from collections import defaultdict

from schema import Claim, SECTION_TITLES

BADGE = {"evidence": "EVIDENCE", "inference": "INFERENCE"}
VERDICTS = {"Invest", "Conditional", "Do Not Invest"}


def render_report(
    indication: str, mechanism: str, claims: list[Claim], cost_summary: str | None = None
) -> str:
    by_section: dict[str, list[Claim]] = defaultdict(list)
    for c in claims:
        by_section[c.section].append(c)

    verdict = next(
        (c.claim for c in by_section.get("recommendation", []) if c.claim in VERDICTS),
        "No verdict produced",
    )

    lines = [
        f"# Investment Underwriting Report: {mechanism} — {indication}",
        f"_Generated {datetime.date.today().isoformat()}_",
        "",
        f"**Recommendation: {verdict}**",
        "",
    ]

    for section, title in SECTION_TITLES.items():
        section_claims = by_section.get(section, [])
        lines.append(f"## {title}")
        if not section_claims:
            lines.append("_No claims generated for this section — insufficient evidence or agent did not respond._")
        for c in section_claims:
            lines.extend(_render_claim(c))
        lines.append("")

    lines.append("## Sources Supporting Major Claims")
    sources = _collect_sources(claims)
    if sources:
        for source, url, date_accessed in sources:
            link = f"[{source}]({url})" if url else source
            lines.append(f"- {link} (accessed {date_accessed})")
    else:
        lines.append("_No evidence-backed sources were collected for this run._")

    if cost_summary:
        lines.append("")
        lines.append("---")
        lines.append(cost_summary)

    return "\n".join(lines)


def _render_claim(c: Claim) -> list[str]:
    badge = BADGE.get(c.type, c.type)
    out = [f"- **{c.claim}** `[{badge}]`"]
    if c.type == "evidence":
        link = f"[{c.source}]({c.url})" if c.url else c.source
        out.append(f"  - source: {link} (accessed {c.date_accessed})")
    else:
        out.append(f"  - reasoning: {c.reasoning} (confidence: {c.confidence})")
    return out


def _collect_sources(claims: list[Claim]) -> list[tuple]:
    seen = set()
    sources = []
    for c in claims:
        if c.type == "evidence" and c.source and c.source not in seen:
            seen.add(c.source)
            sources.append((c.source, c.url, c.date_accessed))
    return sources
